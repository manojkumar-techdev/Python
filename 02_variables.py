# Variables



# Declare a variable
my_name = "Manoj"
print(my_name)



# Updated variable
val = "John"
val = 45
print(val)



# Data type of variable with type() function
my_name = "Manoj"
my_age = 45
print(type(my_name))



# Variables are case-sensitive
my_name = "Manoj"
My_name = "Manoj"
print(my_name)
print(My_name)



# Updating data type in variable
myAge = 100
print(myAge)
myAge = 400
print(myAge)



# Variable naming
# Use a-z, A-Z, 0-9, _
# Keywords cannot be variable name
# Cannot start with a number
# Variables are case sensitive
n = 10
N = 100
N9 = 9
n9 = 9



# Variable techniques for variables with multiple names
# camel case
myFirstName = "Manoj"


# Variable techniques for variables with multiple names
# pascal case
MyMiddleName = "Kumar"


# Variable techniques for variables with multiple names
# snake case
my_last_name = "Gupta"



# Many values to multiple variables
x, y, z = 10, 20, 30
print(x, y, x)
print("------------")
print(x)
print(y)
print(z)


# One value to multiple variables
x = y = z = 100
print(x, y, x)
print("------------")
print(x)
print(y)
print(z)



