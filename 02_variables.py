# Variables



# Declare a variable
my_name = "Manoj"
print(my_name)



# Updated variable
val = "John"
val = 45
print(val)



# Data type of variable with type() function
my_name = "Manoj"
my_age = 45
print(type(my_name))



# Variables are case-sensitive
my_name = "Manoj"
My_name = "Manoj"
print(my_name)
print(My_name)



# Updating data type in variable
myAge = 100
print(myAge)
myAge = 400
print(myAge)



